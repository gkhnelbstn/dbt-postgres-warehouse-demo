-- Green taxi trips, same shape as stg_tlc__yellow_trips. One row per source row.
select
    'green'::text                                 as service_type,
    source_month,
    _source_row                                   as source_row,
    vendorid                                      as vendor_id,
    lpep_pickup_datetime                          as pickup_at,
    lpep_dropoff_datetime                         as dropoff_at,
    passenger_count,
    trip_distance                                 as trip_distance_miles,
    ratecodeid                                    as rate_code_id,
    store_and_fwd_flag = 'Y'                      as is_store_and_forward,
    pulocationid                                  as pickup_zone_id,
    dolocationid                                  as dropoff_zone_id,
    payment_type                                  as payment_type_id,
    trip_type                                     as trip_type_id,
    fare_amount::numeric(12, 2)                   as fare_amount,
    extra::numeric(12, 2)                         as extra_amount,
    mta_tax::numeric(12, 2)                       as mta_tax_amount,
    tip_amount::numeric(12, 2)                    as tip_amount,
    tolls_amount::numeric(12, 2)                  as tolls_amount,
    improvement_surcharge::numeric(12, 2)         as improvement_surcharge_amount,
    congestion_surcharge::numeric(12, 2)          as congestion_surcharge_amount,
    null::numeric(12, 2)                          as airport_fee_amount,
    cbd_congestion_fee::numeric(12, 2)            as cbd_congestion_fee_amount,
    ehail_fee::numeric(12, 2)                     as ehail_fee_amount,
    total_amount::numeric(12, 2)                  as total_amount,
    request_source,
    _source_file                                  as source_file,
    _loaded_at                                    as loaded_at
from {{ source('tlc', 'green_trips') }}
